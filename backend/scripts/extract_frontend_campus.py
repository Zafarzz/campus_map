#!/usr/bin/env python3
"""Extract the campus inventory from the front end, read-only.

Writes a JSON snapshot that the seeder consumes and the drift test compares
against. Reads ``src/data/*`` and never writes to it.

Usage::

    python scripts/extract_frontend_campus.py                      # print a summary
    python scripts/extract_frontend_campus.py --out data/frontend_campus_inventory.json
    python scripts/extract_frontend_campus.py --check              # fail if the committed snapshot is stale
    python scripts/extract_frontend_campus.py --src ../src --json   # raw JSON to stdout

``--check`` is what CI and the test suite use: a non-zero exit means the front
end's campus data changed and a human has to decide whether the seed follows.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

# Importable when run as a script from backend/.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.adapters.frontend.campus_extract import FrontendInventory, extract_inventory
from app.core.config import BACKEND_DIR, get_settings

DEFAULT_SNAPSHOT = BACKEND_DIR / "data" / "frontend_campus_inventory.json"


def build_snapshot(inventory: FrontendInventory) -> dict[str, Any]:
    return {
        "_comment": (
            "Generated by backend/scripts/extract_frontend_campus.py from the front end's "
            "src/data/*.ts. Do not edit by hand. Regenerate with 'make extract'. "
            "The seeder reads this; the drift test compares it against a fresh extraction."
        ),
        "content_hash": inventory.content_hash(),
        **inventory.to_dict(),
    }


def summarise(inventory: FrontendInventory) -> str:
    lines = [
        f"campus      {inventory.campus_id}  ({inventory.campus_name})",
        f"buildings   {len(inventory.buildings)}",
        f"floors      {sum(len(b.floors) for b in inventory.buildings)}",
        f"rooms       {inventory.room_count}  ({inventory.demo_room_count} demo placeholders)",
        f"connectors  {len(inventory.connectors)}",
        f"hash        {inventory.content_hash()}",
        "",
        "per building:",
    ]
    for building in inventory.buildings:
        per_floor = " ".join(f"f{floor.level}={len(floor.rooms)}" for floor in building.floors)
        lines.append(f"  {building.id:<8} {building.short_name:<5} {building.name:<16} {per_floor}")

    ambiguous = inventory.ambiguous_aliases()
    if ambiguous:
        lines += ["", "ambiguous legacy ids (resolution raises rather than guessing):"]
        lines += [f"  {alias} -> {', '.join(sorted(rooms))}" for alias, rooms in sorted(ambiguous.items())]

    if inventory.warnings:
        lines += ["", f"warnings ({len(inventory.warnings)}):"]
        lines += [f"  - {w}" for w in inventory.warnings]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--src", help="path to the front end's src/ (default: FRONTEND_SRC_DIR)")
    parser.add_argument("--out", help=f"write the snapshot here (default: {DEFAULT_SNAPSHOT})")
    parser.add_argument("--json", action="store_true", dest="as_json", help="print the snapshot to stdout")
    parser.add_argument(
        "--check",
        action="store_true",
        help="compare against the committed snapshot and exit 1 if the front end has drifted",
    )
    args = parser.parse_args(argv)

    src = Path(args.src) if args.src else get_settings().frontend_src_path
    try:
        inventory = extract_inventory(src)
    except (FileNotFoundError, ValueError) as exc:
        print(f"extraction failed: {exc}", file=sys.stderr)
        return 2

    snapshot = build_snapshot(inventory)

    if args.check:
        committed_path = Path(args.out) if args.out else DEFAULT_SNAPSHOT
        if not committed_path.exists():
            print(
                f"no committed snapshot at {committed_path}; run without --check to create it",
                file=sys.stderr,
            )
            return 1
        committed = json.loads(committed_path.read_text(encoding="utf-8"))
        if committed.get("content_hash") != snapshot["content_hash"]:
            print(
                "FRONT-END DRIFT\n"
                f"  committed hash : {committed.get('content_hash')}\n"
                f"  current hash   : {snapshot['content_hash']}\n\n"
                "The front end's campus data changed. This is not automatically an error - but the\n"
                "seeded identifiers are the API contract, so a human decides whether the backend\n"
                "follows. Review the diff, then run 'make extract' and re-seed.",
                file=sys.stderr,
            )
            return 1
        print(f"no drift: {committed_path} matches the front end ({snapshot['content_hash'][:12]})")
        return 0

    if args.as_json:
        print(json.dumps(snapshot, indent=2, ensure_ascii=False))
        return 0

    target = Path(args.out) if args.out else None
    if target is not None:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(snapshot, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote {target}")

    print(summarise(inventory))
    return 0


if __name__ == "__main__":
    sys.exit(main())
